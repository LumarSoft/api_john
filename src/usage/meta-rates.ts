export function metaMessageRate(category: string, recipient: string, fallbackMarket: string): number {
  const prefixes: Record<string, string> = {
    '54': 'Argentina',
    '55': 'Brazil',
    '56': 'Chile',
    '57': 'Colombia',
    '52': 'Mexico',
    '51': 'Peru',
    '598': 'Rest of Latin America',
    '595': 'Rest of Latin America',
    '1': 'North America',
    '34': 'Spain',
  }
  const digits = recipient.replace(/\D/g, '')
  const prefix = Object.keys(prefixes)
    .sort((a, b) => b.length - a.length)
    .find(p => digits.startsWith(p))
  const market = prefix ? prefixes[prefix] : fallbackMarket
  const rate = META_RATES[market]?.[category]
  if (rate === undefined) throw new Error(`No Meta rate for ${market}/${category}`)
  return rate
}
